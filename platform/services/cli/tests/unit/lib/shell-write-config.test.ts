import { describe, it, expect, beforeEach, afterEach } from 'vitest';
import { mkdirSync, mkdtempSync, readFileSync, rmSync, writeFileSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { FileServerSpecRepository, Paths } from '@minecraft-docker/shared';
import { parseEnvDocument } from '@minecraft-docker/shared/utils';
import { ShellExecutor } from '../../../src/lib/shell.js';
import { serverSpecRepositories } from '../../../src/lib/server-config.js';

const TEMPLATE_COMPOSE = readFileSync(
  join(dirname(fileURLToPath(import.meta.url)), '../../../templates/servers/_template/docker-compose.yml'),
  'utf-8'
);

// writeConfigValue backs `mcctl config`, whitelist and op. Since #675 it writes
// through the ServerSpec (server.yaml, config.env rendered). config.env is the
// container's env_file, so a line break would add another setting (#726).
describe('ShellExecutor.writeConfigValue', () => {
  let root: string;
  let configPath: string;
  let shell: ShellExecutor;

  beforeEach(() => {
    root = mkdtempSync(join(tmpdir(), 'mcctl-cli-write-config-'));
    mkdirSync(join(root, 'servers', 'alpha'), { recursive: true });
    configPath = join(root, 'servers', 'alpha', 'config.env');
    writeFileSync(configPath, 'TYPE=PAPER\nMOTD=old\nEXTRA_ARGS=\n', 'utf-8');
    writeFileSync(
      join(root, 'servers', 'alpha', 'docker-compose.yml'),
      TEMPLATE_COMPOSE.replace(/mc-template/g, 'mc-alpha').replace('mc-router.host: "template.local"', 'mc-router.host: "alpha.local"')
    );
    writeFileSync(join(root, 'servers', 'compose.yml'), 'include: []\n');
    serverSpecRepositories.create = (p) => new FileServerSpecRepository(p, undefined, undefined, () => []);
    shell = new ShellExecutor(new Paths(root));
  });

  afterEach(() => {
    rmSync(root, { recursive: true, force: true });
  });

  it('writes a multi-word value with § color codes through server.yaml', async () => {
    expect(await shell.writeConfigValue('alpha', 'MOTD', '§6Welcome §lto my server')).toBe(true);
    expect(parseEnvDocument(readFileSync(configPath, 'utf-8')).values.get('MOTD')).toBe('§6Welcome §lto my server');
    expect(readFileSync(configPath, 'utf-8')).toMatch(/^# Generated by mcctl[^\n]*\nTYPE=PAPER\nMOTD=§6Welcome §lto my server\n/);
    expect(readFileSync(join(root, 'servers', 'alpha', 'server.yaml'), 'utf-8')).toContain('MOTD: §6Welcome §lto my server');
  });

  it.each([
    'x\nMODS=http://evil/x.jar',
    'x\rMODS=http://evil/x.jar',
    'x\u0000y',
    'x\u001by',
    'x\u2028y',
    '"" MODS=http://evil/x.jar',
    "'' MODS=http://evil/x.jar",
  ])(
    'refuses %j without writing config.env',
    async (value) => {
      expect(await shell.writeConfigValue('alpha', 'MOTD', value)).toBe(false);
      expect(readFileSync(configPath, 'utf-8')).toBe('TYPE=PAPER\nMOTD=old\nEXTRA_ARGS=\n');
    }
  );

  it.each(['MOTD=x\nMODS', 'MOTD=x', 'A B', '1A', ''])('refuses key %j without writing config.env', async (key) => {
    expect(await shell.writeConfigValue('alpha', key, 'https://example.invalid/payload.jar')).toBe(false);
    expect(readFileSync(configPath, 'utf-8')).toBe('TYPE=PAPER\nMOTD=old\nEXTRA_ARGS=\n');
  });
});
