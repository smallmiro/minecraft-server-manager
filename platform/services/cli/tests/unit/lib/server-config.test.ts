/**
 * CLI ServerSpec writers (#675, ADR-0003 §6) on a temp platform: config
 * writes go through server.yaml, and init --reconfigure re-renders hosts.
 */
import { describe, it, expect, beforeEach, afterEach } from 'vitest';
import { existsSync, mkdirSync, mkdtempSync, readFileSync, rmSync, writeFileSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { FileServerSpecRepository, Paths } from '@minecraft-docker/shared';
import { parseEnvDocument } from '@minecraft-docker/shared/utils';
import { rerenderServers, serverSpecRepositories, writeServerConfig } from '../../../src/lib/server-config.js';

const TEMPLATE = join(dirname(fileURLToPath(import.meta.url)), '../../../templates/servers/_template');
let root: string;
let paths: Paths;

function server(name: string, hosts: string): void {
  mkdirSync(join(root, 'servers', name), { recursive: true });
  writeFileSync(
    join(root, 'servers', name, 'docker-compose.yml'),
    readFileSync(join(TEMPLATE, 'docker-compose.yml'), 'utf-8')
      .replace(/mc-template/g, `mc-${name}`)
      .replace('mc-router.host: "template.local"', `mc-router.host: "${hosts}"`)
  );
  writeFileSync(
    join(root, 'servers', name, 'config.env'),
    readFileSync(join(TEMPLATE, 'config.env'), 'utf-8').replace(/^LEVEL=.*$/m, `LEVEL=${name}`)
  );
}

const read = (...p: string[]) => readFileSync(join(root, 'servers', ...p), 'utf-8');

beforeEach(() => {
  root = mkdtempSync(join(tmpdir(), 'mcctl-cli-spec-'));
  paths = new Paths(root);
  writeFileSync(join(root, 'docker-compose.yml'), 'services: {}\n');
  mkdirSync(join(root, 'servers'));
  writeFileSync(join(root, 'servers', 'compose.yml'), 'include: []\n');
  writeFileSync(join(root, '.env'), 'HOST_IPS=10.0.0.2\n');
  // No runtime: none of these writes changes a world (no docker is ever asked)
  serverSpecRepositories.create = (p) => new FileServerSpecRepository(p);
});

afterEach(() => {
  rmSync(root, { recursive: true, force: true });
});

describe('writeServerConfig', () => {
  it('writes the setting through server.yaml and renders config.env', async () => {
    server('alpha', 'alpha.local');
    await writeServerConfig(paths, 'alpha', { set: { MOTD: 'Hello', MEMORY: '6G' } });
    expect(read('alpha', 'server.yaml')).toContain('memory: 6G');
    const values = parseEnvDocument(read('alpha', 'config.env')).values;
    expect(values.get('MOTD')).toBe('Hello');
    expect(values.get('MEMORY')).toBe('6G');
    expect(read('alpha', 'config.env')).toMatch(/^# Generated by mcctl/);
  });
});

describe('rerenderServers (init --reconfigure)', () => {
  it('re-derives nip.io hosts from the new HOST_IPS and keeps custom hosts', async () => {
    server('factory', 'factory.local,factory.1.2.3.4.nip.io,mc.example.com');
    server('beta', 'beta.local');
    const result = await rerenderServers(paths);
    expect(result).toEqual({ updated: ['beta', 'factory'], failed: [] });
    expect(read("factory", "docker-compose.yml")).toMatch(/mc-router.host: "?factory.local,factory.10.0.0.2.nip.io,mc.example.com"?/);
    expect(read('beta', 'docker-compose.yml')).toContain('beta.10.0.0.2.nip.io');
  });

  it('reports a server it cannot read and goes on', async () => {
    server('good', 'good.local');
    server('bad', 'bad.local');
    writeFileSync(join(root, 'servers', 'bad', 'config.env'), 'MEMORY=${MEM}\n');
    const result = await rerenderServers(paths);
    expect(result.updated).toEqual(['good']);
    expect(result.failed.map((f) => f.server)).toEqual(['bad']);
  });
});

describe('serverSpecReport (mcctl upgrade)', () => {
  it('lists imported, pending and refused servers without writing', async () => {
    const { serverSpecReport } = await import('../../../src/lib/server-config.js');
    server('done', 'done.local');
    await writeServerConfig(paths, 'done', { set: { MOTD: 'x' } });
    server('fresh', 'fresh.local');
    server('broken', 'broken.local');
    writeFileSync(join(root, 'servers', 'broken', 'config.env'), 'MEMORY=${MEM}\n');

    const report = await serverSpecReport(paths);
    expect(report.map((r) => [r.server, r.status])).toEqual([
      ['broken', 'refused'],
      ['done', 'imported'],
      ['fresh', 'pending'],
    ]);
    expect(existsSync(join(root, 'servers', 'fresh', 'server.yaml'))).toBe(false);
  });
});
