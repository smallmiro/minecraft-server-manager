/**
 * FileServerSpecRepository with the Docker renderer (#675, ADR-0003 §2-§3):
 * generated-file header, edit detection and absorption, compose protection,
 * idempotent writes, include entry read-back, storage guard.
 */
import { describe, it, expect, beforeEach, afterEach } from 'vitest';
import { existsSync, mkdirSync, mkdtempSync, readFileSync, rmSync, statSync, writeFileSync } from 'node:fs';
import { createHash } from 'node:crypto';
import { tmpdir } from 'node:os';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import yaml from 'js-yaml';
import { Paths, parseEnvDocument } from '../src/utils/index.js';
import {
  FileServerSpecRepository,
  serverSpecTestHooks,
} from '../src/infrastructure/adapters/server-spec/FileServerSpecRepository.js';
import {
  DockerComposeRenderer,
  type RenderContext,
  type RenderedFile,
} from '../src/infrastructure/adapters/server-spec/DockerComposeRenderer.js';
import { ServerSpecError, type ServerSpecDocument } from '../src/domain/server-spec/ServerSpecDocument.js';
import { WorldAssignmentError } from '../src/domain/services/worldAssignment.js';
import type { IContainerRuntimePort } from '../src/application/ports/outbound/IContainerRuntimePort.js';
import type { ContainerStatus } from '../src/types/index.js';

const TEMPLATE = join(dirname(fileURLToPath(import.meta.url)), '../../cli/templates/servers/_template');
const IP = '192.168.1.10';
const HEADER_RE = /^# Generated by mcctl from server\.yaml; edits are detected \(ADR-0003\)\. mcctl:sha256=([0-9a-f]{64}) spec=([0-9a-f]{12})\n/;

let root: string;
let repo: FileServerSpecRepository;

const sha = (s: string) => createHash('sha256').update(s).digest('hex');
const file = (...p: string[]) => join(root, 'servers', ...p);
const read = (...p: string[]) => readFileSync(file(...p), 'utf-8');

function templateServer(name: string, configEdit: (c: string) => string = (c) => c): void {
  mkdirSync(file(name), { recursive: true });
  writeFileSync(
    file(name, 'docker-compose.yml'),
    readFileSync(join(TEMPLATE, 'docker-compose.yml'), 'utf-8')
      .replace(/mc-template/g, `mc-${name}`)
      .replace('mc-router.host: "template.local"', `mc-router.host: "${name}.local,${name}.${IP}.nip.io"`)
  );
  writeFileSync(
    file(name, 'config.env'),
    configEdit(readFileSync(join(TEMPLATE, 'config.env'), 'utf-8').replace(/^LEVEL=.*$/m, `LEVEL=${name}`))
  );
}

async function rejection(promise: Promise<unknown>): Promise<ServerSpecError> {
  const error = await promise.then(
    () => {
      throw new Error('expected a rejection');
    },
    (e: unknown) => e
  );
  expect(error).toBeInstanceOf(ServerSpecError);
  return error as ServerSpecError;
}

/** load + write, as `mcctl migrate spec` does. */
async function migrate(name: string): Promise<ServerSpecDocument> {
  const loaded = (await repo.load(name))!;
  await repo.write(loaded.document, { expectedRevision: loaded.revision });
  return loaded.document;
}

const mtimes = (name: string) =>
  [file(name, 'server.yaml'), file(name, 'config.env'), file(name, 'docker-compose.yml'), file('compose.yml')].map(
    (p) => statSync(p).mtimeMs
  );

beforeEach(() => {
  root = mkdtempSync(join(tmpdir(), 'mcctl-spec-render-'));
  mkdirSync(join(root, 'servers'));
  writeFileSync(join(root, 'servers', 'global.env'), 'TZ\nEXTRA_ARGS\n');
  writeFileSync(join(root, 'servers', 'compose.yml'), 'include:\n  - other/docker-compose.yml\n');
  writeFileSync(join(root, '.env'), `HOST_IPS=${IP}\n`);
  repo = new FileServerSpecRepository(new Paths(root));
});

afterEach(() => {
  rmSync(root, { recursive: true, force: true });
});

describe('write renders the generated files', () => {
  it('writes server.yaml, then config.env and the compose with the header, and adds the include entry', async () => {
    templateServer('survival');
    const doc = await migrate('survival');

    const specRevision = sha(read('survival', 'server.yaml'));
    for (const name of ['config.env', 'docker-compose.yml']) {
      const text = read('survival', name);
      const match = HEADER_RE.exec(text)!;
      expect(match, name).not.toBeNull();
      expect(match[1]).toBe(sha(text.slice(match[0].length)));
      expect(match[2]).toBe(specRevision.slice(0, 12));
    }
    expect(parseEnvDocument(read('survival', 'config.env')).values.get('LEVEL')).toBe('survival');
    expect((yaml.load(read('compose.yml')) as { include: string[] }).include).toEqual([
      'other/docker-compose.yml',
      'survival/docker-compose.yml',
    ]);
    expect(await repo.load('survival')).toEqual({ document: doc, revision: specRevision, warnings: [] });
  });

  it('imports again to the same document from its own output', async () => {
    templateServer('survival');
    const doc = await migrate('survival');
    rmSync(file('survival', 'server.yaml'));
    expect((await repo.load('survival'))!.document).toEqual(doc);
  });

  it('writes nothing when the spec is unchanged', async () => {
    templateServer('survival');
    const doc = await migrate('survival');
    const before = mtimes('survival');
    await new Promise((r) => setTimeout(r, 20));
    await repo.write(doc);
    await migrate('survival');
    expect(mtimes('survival')).toEqual(before);
  });

  it('keeps config.env comments and untouched lines', async () => {
    templateServer('survival', (c) => c.replace('MOTD=Welcome! Your adventure begins here.', 'MOTD="Quoted" # mine'));
    await migrate('survival');
    const text = read('survival', 'config.env');
    expect(text).toContain('MOTD="Quoted" # mine');
    expect(text).toContain('# Options: peaceful, easy, normal, hard');
  });

  it('refuses a servers/compose.yml it cannot read and writes nothing', async () => {
    templateServer('survival');
    writeFileSync(join(root, 'servers', 'compose.yml'), 'include: [broken\n');
    const before = read('survival', 'config.env');
    const loaded = (await repo.load('survival'))!;
    await rejection(repo.write(loaded.document));
    expect(existsSync(file('survival', 'server.yaml'))).toBe(false);
    expect(read('survival', 'config.env')).toBe(before);
    expect(read('compose.yml')).toBe('include: [broken\n');
  });
});

describe('edit detection on load', () => {
  it('absorbs a hand edit of config.env and re-renders it on the next write', async () => {
    templateServer('survival');
    await migrate('survival');
    writeFileSync(file('survival', 'config.env'), read('survival', 'config.env').replace('PVP=true', 'PVP=false'));

    const loaded = (await repo.load('survival'))!;
    expect(loaded.document.env['PVP']).toBe('false');
    expect(loaded.warnings.join('\n')).toMatch(/config\.env.*absorbed/);

    await repo.write(loaded.document, { expectedRevision: loaded.revision });
    expect(HEADER_RE.test(read('survival', 'config.env'))).toBe(true);
    expect(read('survival', 'config.env')).toContain('PVP=false');
    expect((await repo.load('survival'))!.warnings).toEqual([]);
  });

  it('absorbs a header-less config.env (written by PR 1 era or v2 writers)', async () => {
    templateServer('survival');
    await migrate('survival');
    writeFileSync(
      file('survival', 'config.env'),
      read('survival', 'config.env').replace(HEADER_RE, '').replace('MEMORY=4G', 'MEMORY=6G')
    );
    expect((await repo.load('survival'))!.document.memory).toBe('6G');
  });

  it('renders a hand edit of server.yaml on the next write', async () => {
    templateServer('survival');
    await migrate('survival');
    writeFileSync(file('survival', 'server.yaml'), read('survival', 'server.yaml').replace('memory: 4G', 'memory: 6G'));

    const loaded = (await repo.load('survival'))!;
    expect(loaded.document.memory).toBe('6G');
    expect(loaded.warnings.join('\n')).toMatch(/config\.env.*older than server\.yaml/);
    await repo.write(loaded.document, { expectedRevision: loaded.revision });
    expect(parseEnvDocument(read('survival', 'config.env')).values.get('MEMORY')).toBe('6G');
  });

  it("refuses with 'edit_conflict' when both were edited; --force re-renders from server.yaml after a .bak", async () => {
    templateServer('survival');
    await migrate('survival');
    writeFileSync(file('survival', 'server.yaml'), read('survival', 'server.yaml').replace('memory: 4G', 'memory: 6G'));
    const edited = read('survival', 'config.env').replace('PVP=true', 'PVP=false');
    writeFileSync(file('survival', 'config.env'), edited);

    const error = await rejection(repo.load('survival'));
    expect(error.code).toBe('edit_conflict');
    expect(error.message).toMatch(/mcctl migrate spec survival --force/);

    const fromFile = (await repo.loadFile('survival'))!;
    await expect(repo.write(fromFile.document)).rejects.toMatchObject({ code: 'edit_conflict' });
    await repo.write(fromFile.document, { force: true });
    expect(read('survival', 'config.env.bak')).toBe(edited);
    const values = parseEnvDocument(read('survival', 'config.env')).values;
    expect(values.get('MEMORY')).toBe('6G');
    expect(values.get('PVP')).toBe('true');
  });

  it('refuses an interpolated managed value in an edited config.env', async () => {
    templateServer('survival');
    await migrate('survival');
    writeFileSync(file('survival', 'config.env'), read('survival', 'config.env').replace('MEMORY=4G', 'MEMORY=${MEM}'));
    expect((await rejection(repo.load('survival'))).code).toBe('undetermined');
  });
});

describe('compose edits', () => {
  it('absorbs a hand-edited image and router labels', async () => {
    templateServer('survival');
    await migrate('survival');
    writeFileSync(
      file('survival', 'docker-compose.yml'),
      read('survival', 'docker-compose.yml')
        .replace('itzg/minecraft-server:java25', 'itzg/minecraft-server:java21')
        .replace('survival.local,', 'survival.local,mc.example.com,')
    );
    const loaded = (await repo.load('survival'))!;
    expect(loaded.document.image).toBe('itzg/minecraft-server:java21');
    expect(loaded.document.routing.customHostnames).toEqual(['mc.example.com']);
    expect(loaded.warnings.join('\n')).toMatch(/docker-compose\.yml.*absorbed/);
    await repo.write(loaded.document, { expectedRevision: loaded.revision });
    expect(HEADER_RE.test(read('survival', 'docker-compose.yml'))).toBe(true);
    expect(read('survival', 'docker-compose.yml')).toContain('java21');
  });

  it('overwrites a legacy compose whose only difference is a known variant (env_file ../../.env)', async () => {
    templateServer('survival');
    writeFileSync(file('survival', 'docker-compose.yml'), read('survival', 'docker-compose.yml').replace('- ../global.env', '- ../../.env'));
    const loaded = (await repo.load('survival'))!;
    expect(loaded.warnings.join('\n')).not.toMatch(/protected/);
    await repo.write(loaded.document, { expectedRevision: loaded.revision });
    expect(read('survival', 'docker-compose.yml')).toContain('../global.env');
  });

  describe('a compose edited outside the spec', () => {
    const PORTS = (c: string) => c.replace('    restart: "no"', '    restart: "no"\n    ports:\n      - "25566:25565"');

    beforeEach(async () => {
      templateServer('survival');
      await migrate('survival');
      writeFileSync(file('survival', 'docker-compose.yml'), PORTS(read('survival', 'docker-compose.yml')));
    });

    it('is reported on load with the differing path', async () => {
      const { warnings } = (await repo.load('survival'))!;
      expect(warnings.join('\n')).toMatch(/services\.mc-survival\.ports.*protected/);
    });

    it('is left untouched by a write that does not change the rendered compose', async () => {
      const loaded = (await repo.load('survival'))!;
      await repo.write({ ...loaded.document, memory: '6G' }, { expectedRevision: loaded.revision });
      expect(read('survival', 'docker-compose.yml')).toContain('25566:25565');
      expect(parseEnvDocument(read('survival', 'config.env')).values.get('MEMORY')).toBe('6G');
    });

    it("refuses a compose-changing write with 'compose_edited' before writing anything", async () => {
      const loaded = (await repo.load('survival'))!;
      const yamlBefore = read('survival', 'server.yaml');
      const error = await rejection(
        repo.write({ ...loaded.document, image: 'itzg/minecraft-server:java21' }, { expectedRevision: loaded.revision })
      );
      expect(error.code).toBe('compose_edited');
      expect(error.message).toContain('services.mc-survival.ports');
      expect(read('survival', 'server.yaml')).toBe(yamlBefore);
    });

    it('--force overwrites it after a .bak', async () => {
      const edited = read('survival', 'docker-compose.yml');
      const loaded = (await repo.load('survival'))!;
      await repo.write({ ...loaded.document, image: 'itzg/minecraft-server:java21' }, { force: true });
      expect(read('survival', 'docker-compose.yml.bak')).toBe(edited);
      expect(read('survival', 'docker-compose.yml')).not.toContain('25566');
    });
  });
});

describe('guards', () => {
  it("refuses with 'compose_edited' when the compose no longer parses", async () => {
    templateServer('survival');
    const doc = await migrate('survival');
    writeFileSync(file('survival', 'docker-compose.yml'), 'services: [broken\n');
    const error = await rejection(repo.write({ ...doc, image: 'itzg/minecraft-server:java21' }));
    expect(error.code).toBe('compose_edited');
    expect(error.message).toMatch(/does not parse/);
  });


  it("refuses a storage change without allowStorageChange ('storage_change')", async () => {
    templateServer('survival');
    const doc = await migrate('survival');
    const moved: ServerSpecDocument = { ...doc, world: { ...doc.world, storage: 'data' } };
    expect((await rejection(repo.write(moved))).code).toBe('storage_change');
    const stopped = { getStatus: () => 'exited' } as unknown as IContainerRuntimePort;
    await new FileServerSpecRepository(new Paths(root), undefined, stopped).write(moved, { allowStorageChange: true });
    expect(parseEnvDocument(read('survival', 'config.env')).values.get('EXTRA_ARGS')).toBe('');
  });

  it("refuses to write over a server whose import is refused ('undetermined') unless forced", async () => {
    templateServer('survival');
    const doc = (await repo.load('survival'))!.document;
    writeFileSync(file('survival', 'config.env'), read('survival', 'config.env').replace('MEMORY=4G', 'MEMORY=${MEM}'));
    expect((await rejection(repo.write(doc))).code).toBe('undetermined');
    await repo.write(doc, { force: true });
    expect(parseEnvDocument(read('survival', 'config.env')).values.get('MEMORY')).toBe('4G');
  });
});

describe('servers/compose.yml read-back', () => {
  class DroppingRenderer extends DockerComposeRenderer {
    constructor(private drops: number) {
      super();
    }
    override render(doc: ServerSpecDocument, ctx: RenderContext): RenderedFile[] {
      return super.render(doc, ctx).map((f) =>
        f.path.endsWith(join('servers', 'compose.yml')) && this.drops-- > 0
          ? { ...f, content: 'include:\n  - other/docker-compose.yml\n# lost\n' }
          : f
      );
    }
  }

  it('retries once when the entry is missing after the write', async () => {
    templateServer('survival');
    const doc = (await repo.load('survival'))!.document;
    await new FileServerSpecRepository(new Paths(root), new DroppingRenderer(2)).write(doc);
    expect(read('compose.yml')).toContain('survival/docker-compose.yml');
  });

  it('fails when the entry is still missing after the retry', async () => {
    templateServer('survival');
    const doc = (await repo.load('survival'))!.document;
    const error = await rejection(new FileServerSpecRepository(new Paths(root), new DroppingRenderer(5)).write(doc));
    expect(error.message).toMatch(/servers\/compose\.yml/);
  });
});

describe('world assignment guard on a changed LEVEL (ADR-0003 R4, ADR-0002)', () => {
  const runtime = (status: ContainerStatus) => ({ getStatus: () => status }) as unknown as IContainerRuntimePort;
  const withRuntime = (status: ContainerStatus) => new FileServerSpecRepository(new Paths(root), undefined, runtime(status));

  /** Hand-edit servers/<name>/server.yaml so world.level becomes `level`. */
  function editLevel(name: string, level: string): void {
    writeFileSync(file(name, 'server.yaml'), read(name, 'server.yaml').replace(/^  level: .*$/m, `  level: ${level}`));
  }

  async function worldRejection(promise: Promise<unknown>): Promise<WorldAssignmentError> {
    const error = await promise.then(
      () => {
        throw new Error('expected a rejection');
      },
      (e: unknown) => e
    );
    expect(error).toBeInstanceOf(WorldAssignmentError);
    return error as WorldAssignmentError;
  }

  beforeEach(async () => {
    templateServer('alpha');
    templateServer('beta');
    await migrate('alpha');
    await migrate('beta');
  });

  it("refuses a hand-edited level that another server uses ('conflict') and writes nothing", async () => {
    editLevel('beta', 'alpha');
    const yamlBefore = read('beta', 'server.yaml');
    const configBefore = read('beta', 'config.env');
    repo = withRuntime('exited');

    const error = await worldRejection(migrate('beta'));
    expect(error.code).toBe('conflict');
    expect(error.servers).toEqual(['alpha']);
    expect(read('beta', 'server.yaml')).toBe(yamlBefore);
    expect(read('beta', 'config.env')).toBe(configBefore);
  });

  it("refuses a level change on a running server ('server_running')", async () => {
    editLevel('beta', 'fresh');
    repo = withRuntime('running');
    expect((await worldRejection(migrate('beta'))).code).toBe('server_running');
  });

  it("refuses a level change when the runtime cannot be asked ('undetermined')", async () => {
    editLevel('beta', 'fresh');
    expect((await worldRejection(migrate('beta'))).code).toBe('undetermined');
  });

  it("refuses a level change while another server's world cannot be determined (R7)", async () => {
    writeFileSync(file('alpha', 'config.env'), read('alpha', 'config.env').replace(/^LEVEL=.*$/m, 'LEVEL=${W}'));
    editLevel('beta', 'fresh');
    repo = withRuntime('exited');
    expect((await worldRejection(migrate('beta'))).code).toBe('undetermined');
  });

  it('renders a level change to a free world on a stopped server', async () => {
    editLevel('beta', 'fresh');
    repo = withRuntime('exited');
    await migrate('beta');
    expect(parseEnvDocument(read('beta', 'config.env')).values.get('LEVEL')).toBe('fresh');
  });

  it('does not check (or need a runtime) when the level stays the same', async () => {
    writeFileSync(file('beta', 'server.yaml'), read('beta', 'server.yaml').replace('memory: 4G', 'memory: 6G'));
    await migrate('beta');
    expect(parseEnvDocument(read('beta', 'config.env')).values.get('MEMORY')).toBe('6G');
  });
});

describe('concurrent writers (another process)', () => {
  const sleep = (ms: number) => new Promise((r) => setTimeout(r, ms));
  const defaults = { ...serverSpecTestHooks };

  afterEach(() => {
    Object.assign(serverSpecTestHooks, defaults);
  });

  it('keeps every include entry when two servers are written at the same time', async () => {
    templateServer('alpha');
    templateServer('beta');
    const loaded = [(await repo.load('alpha'))!, (await repo.load('beta'))!];
    // Let both writers reach the include write together; the lock keeps the second one out, so give up after 300 ms.
    let arrived = 0;
    serverSpecTestHooks.beforeIncludeWrite = async () => {
      arrived++;
      const start = Date.now();
      while (arrived < 2 && Date.now() - start < 300) await sleep(10);
    };
    await Promise.all(
      loaded.map((l) => new FileServerSpecRepository(new Paths(root)).write(l.document, { expectedRevision: l.revision }))
    );
    expect((yaml.load(read('compose.yml')) as { include: string[] }).include.sort()).toEqual([
      'alpha/docker-compose.yml',
      'beta/docker-compose.yml',
      'other/docker-compose.yml',
    ]);
    expect(existsSync(file('.compose.yml.lock'))).toBe(false);
  });

  it("refuses with 'locked' while another live process holds servers/compose.yml", async () => {
    templateServer('alpha');
    const holder = {
      pid: process.pid,
      hostname: (await import('node:os')).hostname(),
      bootTime: Math.round(Date.now() - (await import('node:os')).uptime() * 1000),
      nonce: 'someone-else',
      op: 'compose-include',
      startedAt: new Date().toISOString(),
    };
    writeFileSync(file('.compose.yml.lock'), JSON.stringify(holder));
    serverSpecTestHooks.includeLockWaitMs = 100;
    const loaded = (await repo.load('alpha'))!;
    const error = await rejection(repo.write(loaded.document, { expectedRevision: loaded.revision }));
    expect(error.code).toBe('locked');
    expect(error.message).toContain(String(process.pid));
    expect(read('compose.yml')).not.toContain('alpha/docker-compose.yml');
  });

  it("refuses with 'conflict' when server.yaml changes after the checks, writing nothing", async () => {
    templateServer('alpha');
    await migrate('alpha');
    const loaded = (await repo.load('alpha'))!;
    const configBefore = read('alpha', 'config.env');
    serverSpecTestHooks.beforeWrite = async () => {
      writeFileSync(file('alpha', 'server.yaml'), read('alpha', 'server.yaml').replace('memory: 4G', 'memory: 8G'));
    };
    const error = await rejection(repo.write({ ...loaded.document, memory: '6G' }, { expectedRevision: loaded.revision }));
    expect(error.code).toBe('conflict');
    expect(read('alpha', 'server.yaml')).toContain('memory: 8G');
    expect(read('alpha', 'config.env')).toBe(configBefore);
  });

  it("refuses with 'conflict' when a generated file changes after the checks, writing nothing", async () => {
    templateServer('alpha');
    await migrate('alpha');
    const loaded = (await repo.load('alpha'))!;
    const yamlBefore = read('alpha', 'server.yaml');
    serverSpecTestHooks.beforeWrite = async () => {
      writeFileSync(file('alpha', 'config.env'), read('alpha', 'config.env').replace('PVP=true', 'PVP=false'));
    };
    const error = await rejection(repo.write({ ...loaded.document, memory: '6G' }, { expectedRevision: loaded.revision }));
    expect(error.code).toBe('conflict');
    expect(error.message).toContain('config.env');
    expect(read('alpha', 'server.yaml')).toBe(yamlBefore);
    expect(read('alpha', 'config.env')).toContain('PVP=false');
  });
});
