const SPEC_FILE = 'server.yaml';
const HEADER_PREFIX = '# Generated by mcctl from server.yaml; edits are detected (ADR-0003).';
const HEADER_RE = /^# Generated by mcctl from server\.yaml; edits are detected \(ADR-0003\)\. mcctl:sha256=([0-9a-f]{64}) spec=([0-9a-f]{12})\n/;

async function readOptional(file: string): Promise<string | undefined> {
  try {
    return await readFile(file, 'utf-8');
  } catch (err) {
    const code = (err as NodeJS.ErrnoException).code;
    if (code === 'ENOENT' || code === 'ENOTDIR') return undefined;
    throw err;
  }
}

function readOptionalSync(file: string): string | undefined {
  try {
    return readFileSync(file, 'utf-8');
  } catch (err) {
    const code = (err as NodeJS.ErrnoException).code;
    if (code === 'ENOENT' || code === 'ENOTDIR') return undefined;
    throw err;
  }
}

async function isDirectory(path: string): Promise<boolean> {
  try {
    return (await stat(path)).isDirectory();
  } catch {
    return false;
  }
}

/**
 * A generated file split into its mcctl header and body (ADR-0003 §3).
 * `hashOk`: the body is what mcctl wrote. `spec`: the server.yaml revision prefix it was rendered from.
 */
function readHeader(text: string): { body: string; hashOk: boolean; spec?: string } {
  const match = HEADER_RE.exec(text);
  if (!match) return { body: text, hashOk: false };
  const body = text.slice(match[0].length);
  return { body, hashOk: envRevision(body) === match[1], spec: match[2] };
}

function withHeader(body: string, specRevision: string): string {
  return `${HEADER_PREFIX} mcctl:sha256=${envRevision(body)} spec=${specRevision.slice(0, 12)}\n${body}`;
}

/** server.yaml text: fixed key order, absent optional fields omitted, js-yaml quoting. */
function dumpServerSpec(doc: ServerSpecDocument): string {
  const r = doc.routing;
  const ordered = {
    specVersion: doc.specVersion,
    name: doc.name,
    type: doc.type,
    ...(doc.version !== undefined && { version: doc.version }),
    ...(doc.memory !== undefined && { memory: doc.memory }),
    image: doc.image,
    world: { level: doc.world.level, storage: doc.world.storage },
    routing: {
      customHostnames: [...r.customHostnames],
      ...(r.playitDomain !== undefined && { playitDomain: r.playitDomain }),
      autoScale: { up: r.autoScale.up, down: r.autoScale.down },
      ...(r.asleepMotd !== undefined && { asleepMotd: r.asleepMotd }),
      ...(r.loadingMotd !== undefined && { loadingMotd: r.loadingMotd }),
    },
    env: { ...doc.env },
  };
  return yaml.dump(ordered, { lineWidth: -1, noRefs: true, quotingType: '"' });
}

/** Points where tests step in to interleave another writer; no behaviour in production. */
export const serverSpecTestHooks = {
  /** After every check, right before the re-check that precedes the first write. */
  beforeWrite: async (): Promise<void> => {},
  /** Inside the servers/compose.yml lock, after the fresh read, before the write. */
  beforeIncludeWrite: async (): Promise<void> => {},
  /** How long to wait for another process holding servers/compose.yml. */
  includeLockWaitMs: 10_000,
};

const editConflict = (name: string) =>
  new ServerSpecError(
    'edit_conflict',
    `servers/${name}/config.env and server.yaml were both edited since mcctl last wrote them; ` +
      `undo one of the edits, or run mcctl migrate spec ${name} --force to re-render from server.yaml ` +
      '(config.env.bak keeps your config.env)',
    name
  );

/**
 * IServerSpecRepository on the Docker file layout (#675, ADR-0003 §2-§3):
 * servers/<n>/server.yaml is the definition; config.env, the server
 * docker-compose.yml and its servers/compose.yml entry are rendered from it.
 * A server without server.yaml is imported in memory from those files.
 */
export class FileServerSpecRepository implements IServerSpecRepository {
  /**
   * @param runtime asked whether a server is stopped before its world changes; without it such writes are refused (R7).
   * @param hostIps the host addresses for nip.io router hosts (default: resolveHostIps).
   */
  constructor(
    private readonly paths: Paths = new Paths(),
    private readonly renderer: ServerSpecRenderer = new DockerComposeRenderer(),
    private readonly runtime?: IContainerRuntimePort,
    private readonly resolveIps: () => string[] = () => resolveHostIps(paths)
  ) {}

  async list(): Promise<ServerSpec[]> {
    let entries: string[];
    try {
      entries = await readdir(this.paths.servers);
    } catch (err) {
      if ((err as NodeJS.ErrnoException).code === 'ENOENT') return [];
      throw err;
    }
    const names: ServerSpec[] = [];
    for (const name of entries.sort()) {
      if (name.startsWith('_') || !EXISTING_SERVER_NAME_PATTERN.test(name)) continue;
      const dir = this.paths.serverDir(name);
      if (!(await isDirectory(dir))) continue;
      const files = await readdir(dir);
      if (files.includes(SPEC_FILE) || files.includes('config.env')) names.push({ name });
    }
    return names;
  }

  /** @deprecated Use load(). Removed in v3.0.0 (#736). */
  async get(name: string): Promise<ServerSpec | null> {
    return (await this.load(name))?.document ?? null;
  }

  async save(spec: ServerSpec): Promise<void> {
    await this.write(spec as ServerSpecDocument);
  }

  async delete(name: string): Promise<void> {
    throw new ServerSpecError(
      'conflict',
      `Removing server '${name}' through the ServerSpec repository arrives with #735; use mcctl delete ${name}`,
      name
    );
  }

  /**
   * The spec with hand edits of the generated files absorbed (ADR-0003 §3),
   * or imported in memory when server.yaml is missing. Never writes.
   */
  async load(name: string): Promise<LoadedServerSpec | null> {
    if (!EXISTING_SERVER_NAME_PATTERN.test(name)) return null;
    const dir = this.paths.serverDir(name);
    const hostIps = await this.hostIps();
    const text = await readOptional(join(dir, SPEC_FILE));
    if (text === undefined) {
      if ((await readOptional(join(dir, 'config.env'))) === undefined) return null;
      const result = await this.importServer(name, hostIps);
      if (result.status === 'refused') {
        throw new ServerSpecError('undetermined', `Cannot import server '${name}': ${result.reason}`, name);
      }
      const compose = (await readOptional(join(dir, 'docker-compose.yml')))!;
      const warnings = [...result.warnings, ...this.protectedWarnings(result.document, compose, true, hostIps)];
      return { document: result.document, revision: null, warnings };
    }

    const revision = envRevision(text);
    let doc = this.parse(name, text);
    const warnings: string[] = [];

    const config = await readOptional(join(dir, 'config.env'));
    if (config !== undefined) {
      const header = readHeader(config);
      const current = header.spec === revision.slice(0, 12);
      if (!header.hashOk) {
        if (header.spec !== undefined && !current) throw editConflict(name);
        const notes: string[] = [];
        const absorbed = await absorbConfigEnv(doc, header.body, this.paths, notes);
        if (dumpServerSpec(absorbed) !== dumpServerSpec(doc)) {
          warnings.push(`servers/${name}/config.env was edited by hand; the edits are absorbed into the spec`, ...notes);
          doc = absorbed;
        }
      } else if (!current) {
        warnings.push(`servers/${name}/config.env is older than server.yaml; the next write renders it`);
      }
    }

    const compose = await readOptional(join(dir, 'docker-compose.yml'));
    if (compose !== undefined) {
      const header = readHeader(compose);
      if (!header.hashOk) {
        const notes: string[] = [];
        const absorbed = absorbCompose(doc, header.body, hostIps, notes);
        if (dumpServerSpec(absorbed) !== dumpServerSpec(doc)) {
          warnings.push(`servers/${name}/docker-compose.yml image or router labels were edited by hand; absorbed into the spec`, ...notes);
          doc = absorbed;
        }
        warnings.push(...this.protectedWarnings(doc, header.body, false, hostIps));
      }
    }
    return { document: doc, revision, warnings };
  }

  /** server.yaml as written, without absorbing edits of the generated files (`mcctl migrate spec --force`). */
  async loadFile(name: string): Promise<LoadedServerSpec | null> {
    if (!EXISTING_SERVER_NAME_PATTERN.test(name)) return null;
    const text = await readOptional(join(this.paths.serverDir(name), SPEC_FILE));
    if (text === undefined) return null;
    return { document: this.parse(name, text), revision: envRevision(text), warnings: [] };
  }

  /**
   * Write server.yaml, then render the generated files (ADR-0003 §2-§3).
   * Every check runs before the first write. Unchanged files are not written.
   * All or nothing per file: when a write fails, the files this write already
   * changed get their earlier content back (or are removed when new), so a
   * caller undoing its own steps (migrate worlds) matches the files.
   */
  async write(doc: ServerSpecDocument, options: WriteServerSpecOptions = {}): Promise<void> {
    if (options.create) return this.create(doc);
    const server = typeof doc?.name === 'string' ? doc.name : '?';
    assertServerSpecDocument(doc, 'existing', { server, file: `servers/${server}/${SPEC_FILE}` });
    const name = doc.name;
    const dir = this.paths.serverDir(name);
    if (!(await isDirectory(dir))) {
      throw new ServerSpecError('not_found', `Server '${name}' not found (no servers/${name} directory)`, name);
    }
    const specPath = join(dir, SPEC_FILE);
    const currentYaml = await readOptional(specPath);
    const revision = currentYaml === undefined ? null : envRevision(currentYaml);
    if (options.expectedRevision !== undefined && revision !== options.expectedRevision) {
      throw new ServerSpecError(
        'conflict',
        `servers/${name}/${SPEC_FILE} changed since it was read; load it again and retry`,
        name
      );
    }

    const hostIps = await this.hostIps();
    const previous = await this.previous(name, currentYaml, hostIps, options.force);
    if (previous && previous.world.storage !== doc.world.storage && !options.allowStorageChange) {
      throw new ServerSpecError(
        'storage_change',
        `Changing where server '${name}' keeps its world (${previous.world.storage} → ${doc.world.storage}) ` +
          'moves the world; use mcctl migrate worlds',
        name
      );
    }

    const nextYaml = dumpServerSpec(doc);
    const nextRevision = envRevision(nextYaml);
    const ctx = this.renderContext(hostIps);
    const plan: Array<{ path: string; content: string; before?: string; backup?: string }> = [];
    let include: RenderedFile | undefined;
    for (const file of this.renderer.render(doc, ctx)) {
      const current = readOptionalSync(file.path);
      if (!file.guarded) {
        if (current !== file.content) include = file;
        continue;
      }
      const content = withHeader(file.content, nextRevision);
      if (current === content) continue;
      const header = current === undefined ? undefined : readHeader(current);
      if (!header || header.hashOk) {
        plan.push({ path: file.path, content, before: current });
      } else if (basename(file.path) === 'config.env') {
        // Hand edits are absorbed by load(); both edited (a stale spec= with a bad hash) is a conflict.
        const bothEdited = revision !== null && header.spec !== undefined && header.spec !== revision.slice(0, 12);
        if (bothEdited && !options.force) throw editConflict(name);
        plan.push({ path: file.path, content, before: current, ...(bothEdited && { backup: current }) });
      } else {
        const outside = composeOutsideEdits(name, header.body, file.content, revision === null);
        if (outside.length === 0) {
          plan.push({ path: file.path, content, before: current });
        } else if (options.force) {
          plan.push({ path: file.path, content, before: current, backup: current });
        } else {
          const before = previous && this.renderer.render(previous, this.withoutInclude(ctx)).find((f) => f.path === file.path);
          if (before?.content === file.content) continue; // this write does not change the compose: leave the edits alone
          throw new ServerSpecError(
            'compose_edited',
            `servers/${name}/docker-compose.yml has edits outside the spec (${outside.join(', ')}) that this change ` +
              `would overwrite; revert them, or run mcctl migrate spec ${name} --force (docker-compose.yml.bak keeps them)`,
            name
          );
        }
      }
    }

    const config = plan.find((step) => basename(step.path) === 'config.env');
    if (config) await this.checkWorldChange(name, readHeader(config.content).body);

    // Everything above awaited (host addresses, import, world snapshot): re-read what
    // the plan was built on right before the first write, so a writer that came in
    // meanwhile is not overwritten. ponytail: what remains is the temp-file write and
    // fsync of atomicWriteFile (milliseconds); add a per-server lock if lost updates
    // are ever observed.
    await serverSpecTestHooks.beforeWrite();
    if ((await readOptional(specPath)) !== currentYaml) {
      throw new ServerSpecError(
        'conflict',
        `servers/${name}/${SPEC_FILE} changed while this write was checked; load it again and retry`,
        name
      );
    }
    for (const step of plan) {
      if ((await readOptional(step.path)) !== step.before) {
        throw new ServerSpecError(
          'conflict',
          `servers/${name}/${basename(step.path)} changed while this write was checked; load it again and retry`,
          name
        );
      }
    }

    const written: Array<{ path: string; before: string | undefined }> = [];
    const put = async (path: string, content: string, before: string | undefined, opts: AtomicWriteOptions = {}) => {
      await atomicWriteFile(path, content, opts);
      written.push({ path, before });
    };
    try {
      if (currentYaml !== nextYaml) {
        const mode = currentYaml === undefined ? await this.fileMode(join(dir, 'config.env')) : undefined;
        await put(specPath, nextYaml, currentYaml, mode === undefined ? {} : { mode });
      }
      for (const step of plan) {
        if (step.backup !== undefined) {
          const bak = `${step.path}.bak`;
          const mode = await this.fileMode(step.path);
          await put(bak, step.backup, await readOptional(bak), mode === undefined ? {} : { mode });
        }
        await put(step.path, step.content, step.before);
      }
      if (include) await this.writeInclude(name, doc, ctx);
    } catch (err) {
      // A restore failure never hides the write error: it is added to the message (as create's cleanup).
      const failed: string[] = [];
      for (const { path, before } of written.reverse()) {
        await (before === undefined ? rm(path, { force: true }) : atomicWriteFile(path, before)).catch(
          (e: unknown) => void failed.push(`servers/${name}/${basename(path)}: ${(e as Error).message}`)
        );
      }
      if (failed.length > 0 && err instanceof Error) {
        err.message += ` (restoring the earlier files failed: ${failed.join('; ')}; check them by hand)`;
      }
      throw err;
    }
  }

  /**
   * ADR-0003 R4: when the rendered config.env moves the server's world
   * (LEVEL or storage), apply ADR-0002 to the snapshot with that config.env:
   * R1 (no other holder), R7 (every server determined), server stopped.
   * Uses the snapshot reader directly, not IWorldAssignmentPort, because the
   * assignment adapter writes through this repository (ADR-0003 §2).
   * Rejects WorldAssignmentError.
   */
  private async checkWorldChange(name: string, configEnv: string): Promise<void> {
    const current = await readWorldAssignmentSnapshot(this.paths);
    const next = await readWorldAssignmentSnapshot(this.paths, { server: name, content: configEnv });
    const key = (s: WorldAssignmentSnapshot) => {
      const a = s.assignments.find((x) => x.server === name);
      return a ? `${a.world}\0${!!a.internal}` : undefined;
    };
    if (key(current) === key(next)) return;
    const refused = checkProposed(next, name) ?? checkServerStopped(this.runtime, name);
    if (refused) throw refused;
  }

  private async importServer(name: string, hostIps: string[]): Promise<ServerSpecImport> {
    return importDockerServer(name, { paths: this.paths, hostIps });
  }

  /** The spec before this write: server.yaml, else the import (a refused import blocks unless forced). */
  private async previous(
    name: string,
    currentYaml: string | undefined,
    hostIps: string[],
    force?: boolean
  ): Promise<ServerSpecDocument | undefined> {
    if (currentYaml !== undefined) {
      try {
        return this.parse(name, currentYaml);
      } catch {
        return undefined;
      }
    }
    if ((await readOptional(join(this.paths.serverDir(name), 'config.env'))) === undefined) return undefined;
    const result = await this.importServer(name, hostIps);
    if (result.status === 'imported') return result.document;
    if (force) return undefined;
    throw new ServerSpecError(
      'undetermined',
      `Cannot import server '${name}': ${result.reason}; writes are refused until the file is fixed`,
      name
    );
  }

  /**
   * A new server (ADR-0003 §5): claim servers/<n> with mkdir, write
   * server.yaml and the generated files, create data/, logs/ and
   * servers/global.env, then add the include entry. All or nothing: on any
   * failure after the claim the entry it added and the directory are
   * removed, so the same create can be retried at once (#657).
   */
  private async create(input: ServerSpecDocument): Promise<void> {
    const server = typeof input?.name === 'string' ? input.name : '?';
    assertServerSpecDocument(input, 'create', { server, file: `servers/${server}/${SPEC_FILE}` });
    const name = input.name;
    const dir = this.paths.serverDir(name);
    await mkdir(this.paths.servers, { recursive: true });
    try {
      await mkdir(dir);
    } catch (err) {
      if ((err as NodeJS.ErrnoException).code === 'EEXIST') {
        throw new ServerSpecError('already_exists', `Server '${name}' already exists (servers/${name})`, name);
      }
      throw err;
    }

    let entryAdded = false;
    try {
      const doc = this.withTemplateEnv(input);
      const ctx = this.renderContext(await this.hostIps());
      const files = this.renderer.render(doc, ctx); // refuses an unreadable servers/compose.yml
      const config = files.find((f) => basename(f.path) === 'config.env');
      if (config) {
        // R1/R7 for the new server's world; it has no container yet, so no stop check.
        const refused = checkProposed(
          await readWorldAssignmentSnapshot(this.paths, { server: name, content: config.content }),
          name
        );
        if (refused) throw refused;
      }
      const yamlText = dumpServerSpec(doc);
      const revision = envRevision(yamlText);
      await atomicWriteFile(join(dir, SPEC_FILE), yamlText, { mode: 0o600 });
      for (const file of files) {
        if (file.guarded) await atomicWriteFile(file.path, withHeader(file.content, revision));
      }
      await mkdir(join(dir, 'data'), { recursive: true });
      await mkdir(join(dir, 'logs'), { recursive: true });
      const globalEnv = join(this.paths.servers, 'global.env');
      if (readOptionalSync(globalEnv) === undefined) {
        const bundled = readOptionalSync(join(this.paths.templates, 'servers', 'global.env'));
        if (bundled !== undefined) await atomicWriteFile(globalEnv, bundled);
      }
      entryAdded = !includeEntries(readOptionalSync(join(this.paths.servers, 'compose.yml'))).includes(
        `${name}/docker-compose.yml`
      );
      await this.writeInclude(name, doc, ctx);
    } catch (err) {
      // A cleanup failure never hides the create error: it is added to the message (as withCleanup, ADR B5.9).
      const failed: string[] = [];
      const note = (what: string) => (e: unknown) => void failed.push(`${what}: ${(e as Error).message}`);
      if (entryAdded) await this.removeInclude(name).catch(note(`the servers/compose.yml entry for ${name}`));
      await rm(dir, { recursive: true, force: true }).catch(note(`servers/${name}`));
      if (failed.length > 0 && err instanceof Error) {
        err.message += ` (cleanup failed: ${failed.join('; ')}; remove it by hand before retrying)`;
      }
      throw err;
    }
  }

  /**
   * A new spec's env starts from the bundled template's config.env keys
   * (minus the managed ones and EXTRA_ARGS, which world.storage renders), in
   * template order; the document's own values win (create-server.sh copied
   * the template and changed lines).
   */
  private withTemplateEnv(doc: ServerSpecDocument): ServerSpecDocument {
    const template = readOptionalSync(join(this.paths.templates, 'servers', '_template', 'config.env'));
    if (template === undefined) {
      throw new Error(`Bundled server template missing under ${this.paths.templates}; reinstall mcctl`);
    }
    const env: Record<string, string> = {};
    for (const [key, value] of parseEnvDocument(template).values) {
      if (key in SERVER_SPEC_MANAGED_ENV_KEYS || key === 'EXTRA_ARGS') continue;
      env[key] = doc.env[key] ?? value;
    }
    return { ...doc, env: { ...env, ...doc.env } };
  }

  /**
   * Run `fn` on servers/compose.yml under servers/.compose.yml.lock. The file
   * is shared by every server and by CLI and API processes.
   */
  private async withIncludeLock<T>(name: string, fn: () => Promise<T>): Promise<T> {
    const lock = await acquireFileLock(join(this.paths.servers, '.compose.yml.lock'), 'compose-include', {
      waitMs: serverSpecTestHooks.includeLockWaitMs,
      pollMs: 50,
    });
    if (!lock.ok) {
      const who = lock.holder ? ` by pid ${lock.holder.pid} since ${lock.holder.startedAt}` : '';
      throw new ServerSpecError(
        'locked',
        `servers/compose.yml is locked${who} (another mcctl process is changing it); retry in a moment`,
        name
      );
    }
    try {
      return await fn();
    } finally {
      await lock.release();
    }
  }

  /**
   * Add the server's servers/compose.yml entry under the lock: read the file
   * fresh, merge, write, read back and check every entry it had plus ours
   * (one retry for a writer that ignores the lock).
   */
  private async writeInclude(name: string, doc: ServerSpecDocument, ctx: RenderContext): Promise<void> {
    const ok = await this.withIncludeLock(name, async () => {
      const path = join(this.paths.servers, 'compose.yml');
      const expected = [...includeEntries(readOptionalSync(path)), `${name}/docker-compose.yml`];
      for (let attempt = 0; attempt < 2; attempt++) {
        const file = this.renderer.render(doc, ctx).find((f) => !f.guarded)!; // reads the file fresh
        await serverSpecTestHooks.beforeIncludeWrite();
        if (readOptionalSync(file.path) !== file.content) await atomicWriteFile(file.path, file.content);
        const written = includeEntries(readOptionalSync(file.path));
        if (expected.every((entry) => written.includes(entry))) return true;
      }
      return false;
    });
    if (ok) return;
    throw new ServerSpecError(
      'conflict',
      `servers/compose.yml lost entries after a retry (a process that does not take servers/.compose.yml.lock is writing it); ` +
        `run mcctl migrate spec ${name}`,
      name
    );
  }

  /** Remove the server's servers/compose.yml entry (exact name) under the lock. */
  private async removeInclude(name: string): Promise<void> {
    await this.withIncludeLock(name, async () => {
      const path = join(this.paths.servers, 'compose.yml');
      const current = readOptionalSync(path);
      if (current === undefined) return;
      const next = removeIncludeEntry(current, name);
      if (next !== current) await atomicWriteFile(path, next);
    });
  }



  private protectedWarnings(doc: ServerSpecDocument, compose: string, environmentMoved: boolean, hostIps: string[]): string[] {
    const path = join(this.paths.serverDir(doc.name), 'docker-compose.yml');
    const rendered = this.renderer.render(doc, this.withoutInclude(this.renderContext(hostIps))).find((f) => f.path === path);
    if (!rendered) return [];
    const outside = composeOutsideEdits(doc.name, compose, rendered.content, environmentMoved);
    return outside.length === 0
      ? []
      : [
          `servers/${doc.name}/docker-compose.yml has edits outside the spec (${outside.join(', ')}); it is protected: ` +
            `writes that change it fail with compose_edited until you revert them or run mcctl migrate spec ${doc.name} --force`,
        ];
  }

  private renderContext(hostIps: string[]): RenderContext {
    return {
      root: this.paths.root,
      templatesDir: this.paths.templates,
      hostIps,
      read: (path) => {
        const text = readOptionalSync(path);
        return text === undefined ? undefined : readHeader(text).body;
      },
    };
  }

  /** A context that does not read servers/compose.yml: for renders whose include entry is not used. */
  private withoutInclude(ctx: RenderContext): RenderContext {
    const include = join(this.paths.servers, 'compose.yml');
    return { ...ctx, read: (path) => (path === include ? undefined : ctx.read(path)) };
  }

  private parse(name: string, text: string): ServerSpecDocument {
    const file = `servers/${name}/${SPEC_FILE}`;
    let value: unknown;
    try {
      value = yaml.load(text, { schema: yaml.CORE_SCHEMA });
    } catch (e) {
      throw new ServerSpecError(
        'invalid_spec',
        `${file} is not valid YAML: ${(e as Error).message.split('\n')[0]}; fix it, or delete it to import the server again`,
        name
      );
    }
    const doc = assertServerSpecDocument(value, 'existing', { server: name, file });
    if (doc.name !== name) {
      throw new ServerSpecError(
        'invalid_spec',
        `${file} has name '${doc.name}'; it must match its directory '${name}'`,
        name,
        [{ path: 'name', message: `must be '${name}'` }]
      );
    }
    return doc;
  }

  /** server.yaml and .bak files hold config values (secrets included): they get the source file's mode. */
  private async fileMode(path: string): Promise<number | undefined> {
    try {
      return (await stat(path)).mode & 0o777;
    } catch {
      return undefined;
    }
  }

  private async hostIps(): Promise<string[]> {
    return this.resolveIps();
  }
}
